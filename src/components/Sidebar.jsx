/**
 * Main application sidebar navigation for RupeeWise.
 * Displays the primary brand header and section navigation items.
 *
 * @param {Object} props
 * @param {string} props.activeSection
 * @param {Function} props.onNavigate
 * @param {boolean} props.isOpen
 * @param {Function} props.onClose
 */
function Sidebar({ activeSection, onNavigate, isOpen, onClose }) {
  return (
    <>
      {/* Mobile backdrop */}
      {isOpen && (
        <div
          className="sidebar-overlay"
          onClick={onClose}
          aria-hidden="true"
        />
      )}

      <aside className={`sidebar ${isOpen ? 'sidebar--open' : ''}`} aria-label="Main navigation">
        {/* Single primary brand header */}
        <div className="sidebar-header">
          <div className="sidebar-brand">
            <span className="sidebar-brand-logo">
              <RupeeLogo size={32} />
            </span>
            <div className="sidebar-brand-text">
              <span className="sidebar-brand-name">RupeeWise</span>
              <span className="sidebar-brand-tagline">Your money, in focus.</span>
            </div>
          </div>
          {/* Mobile close button */}
          <button
            type="button"
            className="sidebar-close-btn"
            onClick={onClose}
            aria-label="Close navigation"
          >
            <svg viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2" strokeLinecap="round" strokeLinejoin="round" aria-hidden="true">
              <line x1="18" y1="6" x2="6" y2="18" />
              <line x1="6" y1="6" x2="18" y2="18" />
            </svg>
          </button>
        </div>

        {/* Navigation list */}
        <nav className="sidebar-nav-container" aria-label="Sidebar navigation">
          <ul className="sidebar-nav" role="list">
            {NAV_ITEMS.map((item) => (
              <li key={item.id}>
                <button
                  type="button"
                  className={`sidebar-nav-item ${activeSection === item.id ? 'sidebar-nav-item--active' : ''}`}
                  onClick={() => {
                    onNavigate(item.id);
                    onClose();
                  }}
                  aria-current={activeSection === item.id ? 'page' : undefined}
                >
                  <span className="sidebar-nav-icon">{item.icon}</span>
                  <span className="sidebar-nav-label">{item.label}</span>
                </button>
              </li>
            ))}
          </ul>
        </nav>

        {/* Minimal footer */}
        <div className="sidebar-footer">
          <span className="sidebar-footer-text">RupeeWise v2.0</span>
        </div>
      </aside>
    </>
  );
}

export default Sidebar;
